HEAP = 3 << 32

ACC = 0x000
NUM = 0x200
PIDP = 0x208
CLK = 0x210
OUT = 0x240
BUMP = 0x260
SEEDS = 0x270
SIGNERS = 0x2B0
SYSD = 0x2C0
IX = 0x2F0
S0, S1, S2, S3, S4, S5, S6, S7 = (0x320 + 8 * i for i in range(8))
VKEY = 0x360
IDB = 0x380
KEYS = 0x390
METAS = 0x4D0
SLICE = 0x5D0
INFOS = 0x600
VSEEDS = 0x1600
WBUMP = 0x1640
RENT = 0x1648
MAX_ACCOUNTS = 64

ACC_SIGNER = 1
ACC_WRITABLE = 2
ACC_EXEC = 3
ACC_KEY = 8
ACC_OWNER = 40
ACC_LAMPORTS = 72
ACC_DLEN = 80
ACC_DATA = 88

MS_MAGIC = int.from_bytes(M.MS_MAGIC, "little")
PR_MAGIC = int.from_bytes(M.PR_MAGIC, "little")


def heap_ptr(a, reg, off):
    a.mov(reg, r9)
    a.add(reg, off)


def prog_id(a, reg):
    a.ldx(8, reg, r9, PIDP)


def acc(a, reg, idx):
    a.ldx(8, reg, r9, ACC + 8 * idx)


def copy(a, dst, doff, src, soff, n, tmp=r0):
    for i in range(0, n, 8):
        a.ldx(8, tmp, src, soff + i)
        a.stx(8, dst, doff + i, tmp)


def set_seed(a, idx, addr_reg, length):
    a.stx(8, r9, SEEDS + 16 * idx, addr_reg)
    if isinstance(length, int):
        a.st(8, r9, SEEDS + 16 * idx + 8, length)
    else:
        a.stx(8, r9, SEEDS + 16 * idx + 8, length)


def need(a, n):
    a.ldx(8, r0, r9, NUM)
    a.jlt(r0, n, "err3")


def flag(a, idx, off, err):
    acc(a, r1, idx)
    a.ldx(1, r0, r1, off)
    a.jeq(r0, 0, err)


def is_zero32(a, ptr_reg, err):
    for i in range(4):
        a.ldx(8, r0, ptr_reg, 8 * i)
        a.jne(r0, 0, err)


def eq_keys(a, p1, p2, err_if_ne):
    if p1 != r1:
        a.mov(r1, p1)
    if p2 != r2:
        a.mov(r2, p2)
    a.call("eq32")
    a.jne(r0, 0, err_if_ne)


def build(opeq_program):
    if len(opeq_program) != 32:
        raise ValueError("the OPEQ program id must be 32 bytes")
    a = Asm()
    a.data("version", b"opeq/1.0 vault")
    a.data("opeq_id", opeq_program)
    a.data("seed_w", b"w")
    a.data("seed_m", b"m")
    a.data("seed_v", b"v")
    a.data("seed_p", b"p")

    a.label("entrypoint")
    a.mov(r8, r2)
    a.ldx(8, r7, r8, -8)
    a.lddw(r9, HEAP)
    a.mov(r0, r8)
    a.add(r0, r7)
    a.stx(8, r9, PIDP, r0)
    a.ldx(8, r3, r1, 0)
    a.jgt(r3, MAX_ACCOUNTS, "err2")
    a.stx(8, r9, NUM, r3)
    a.mov(r4, r1)
    a.add(r4, 8)
    a.mov(r5, 0)
    a.label("walk")
    a.jge(r5, r3, "walked")
    a.ldx(1, r0, r4, 0)
    a.mov(r6, r5)
    a.lsh(r6, 3)
    a.add(r6, r9)
    a.jne(r0, 0xFF, "walk_dup")
    a.stx(8, r6, ACC, r4)
    a.ldx(8, r0, r4, ACC_DLEN)
    a.add(r0, 7)
    a.and_(r0, -8)
    a.add(r0, 10336)
    a.add(r4, r0)
    a.add(r5, 1)
    a.ja("walk")
    a.label("walk_dup")
    a.lsh(r0, 3)
    a.add(r0, r9)
    a.ldx(8, r0, r0, ACC)
    a.stx(8, r6, ACC, r0)
    a.add(r4, 8)
    a.add(r5, 1)
    a.ja("walk")
    a.label("walked")
    a.jeq(r7, 0, "err1")
    a.ldx(1, r0, r8, 0)
    a.jeq(r0, M.IX_CREATE, "do_create")
    a.jeq(r0, M.IX_PROPOSE, "do_propose")
    a.jeq(r0, M.IX_APPROVE, "do_vote")
    a.jeq(r0, M.IX_REVOKE, "do_vote")
    a.jeq(r0, M.IX_CANCEL, "do_cancel")
    a.jeq(r0, M.IX_EXECUTE, "do_execute")
    a.jeq(r0, M.IX_CLOSE, "do_close")
    a.jeq(r0, M.IX_SWEEP, "do_sweep")
    a.ja("err1")

    emit_create(a)
    emit_propose(a)
    emit_vote(a)
    emit_cancel(a)
    emit_execute(a)
    emit_close(a)
    emit_sweep(a)

    for code in sorted(M.ERRORS):
        a.label(f"err{code}")
        a.mov(r0, code)
        a.exit()
    a.label("fail")
    a.exit()

    emit_eq32(a)
    emit_build_infos(a)
    emit_derive_owner(a)
    emit_validate_owners(a)
    emit_load_ms(a)
    emit_owner_index(a)
    emit_vault_key(a)
    emit_load_proposal(a)
    emit_live(a)
    emit_check_stored(a)
    emit_rent(a)
    emit_sys(a)
    emit_internal(a)
    return a


def emit_eq32(a):
    a.label("eq32")
    for i in range(4):
        a.ldx(8, r6, r1, 8 * i)
        a.ldx(8, r7, r2, 8 * i)
        a.jne(r6, r7, "eq32_ne")
    a.mov(r0, 0)
    a.exit()
    a.label("eq32_ne")
    a.mov(r0, 1)
    a.exit()


def emit_build_infos(a):
    a.label("build_infos")
    a.ldx(8, r3, r9, NUM)
    a.mov(r5, 0)
    heap_ptr(a, r4, INFOS)
    a.label("bi_loop")
    a.jge(r5, r3, "bi_done")
    a.mov(r1, r5)
    a.lsh(r1, 3)
    a.add(r1, r9)
    a.ldx(8, r1, r1, ACC)
    for field, off in ((0, ACC_KEY), (8, ACC_LAMPORTS), (24, ACC_DATA), (32, ACC_OWNER)):
        a.mov(r0, r1)
        a.add(r0, off)
        a.stx(8, r4, field, r0)
    a.ldx(8, r0, r1, ACC_DLEN)
    a.stx(8, r4, 16, r0)
    a.st(8, r4, 40, -1)
    a.st(8, r4, 48, 0)
    for field, off in ((48, ACC_SIGNER), (49, ACC_WRITABLE), (50, ACC_EXEC)):
        a.ldx(1, r0, r1, off)
        a.stx(1, r4, field, r0)
    a.add(r4, 56)
    a.add(r5, 1)
    a.ja("bi_loop")
    a.label("bi_done")
    a.exit()


def emit_derive_owner(a):
    a.label("derive_owner")
    a.mov(r6, r1)
    a.lddw(r2, "seed_w")
    set_seed(a, 0, r2, 1)
    set_seed(a, 1, r1, 32)
    heap_ptr(a, r1, SEEDS)
    a.mov(r2, 2)
    a.lddw(r3, "opeq_id")
    heap_ptr(a, r4, OUT)
    heap_ptr(a, r5, WBUMP)
    a.syscall("sol_try_find_program_address")
    a.jne(r0, 0, "do_ret8")
    a.ldx(1, r0, r9, WBUMP)
    a.ldx(1, r1, r6, 32)
    a.jne(r0, r1, "do_ret8")
    a.mov(r0, 0)
    a.exit()
    a.label("do_ret8")
    a.mov(r0, 8)
    a.exit()


def emit_validate_owners(a):
    a.label("validate_owners")
    a.stx(8, r9, S6, r1)
    a.stx(8, r9, S7, r2)
    a.mov(r6, 0)
    a.label("vo_loop")
    a.ldx(8, r0, r9, S7)
    a.jge(r6, r0, "vo_done")
    a.mov(r1, r6)
    a.mul(r1, 33)
    a.ldx(8, r0, r9, S6)
    a.add(r1, r0)
    a.call("derive_owner")
    a.jne(r0, 0, "vo_ret")
    a.mov(r1, r6)
    a.lsh(r1, 5)
    a.add(r1, r9)
    a.add(r1, KEYS)
    copy(a, r1, 0, r9, OUT, 32)
    a.mov(r7, 0)
    a.label("vo_dup")
    a.jge(r7, r6, "vo_next")
    a.mov(r1, r7)
    a.lsh(r1, 5)
    a.add(r1, r9)
    a.add(r1, KEYS)
    a.mov(r2, r6)
    a.lsh(r2, 5)
    a.add(r2, r9)
    a.add(r2, KEYS)
    a.call("eq32")
    a.jeq(r0, 0, "vo_dup_err")
    a.add(r7, 1)
    a.ja("vo_dup")
    a.label("vo_next")
    a.add(r6, 1)
    a.ja("vo_loop")
    a.label("vo_done")
    a.mov(r0, 0)
    a.label("vo_ret")
    a.exit()
    a.label("vo_dup_err")
    a.mov(r0, 9)
    a.exit()


