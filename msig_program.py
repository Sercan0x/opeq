def emit_vault_key(a):
    a.label("vault_key")
    a.lddw(r2, "seed_v")
    set_seed(a, 0, r2, 1)
    a.mov(r2, r1)
    a.add(r2, ACC_KEY)
    set_seed(a, 1, r2, 32)
    a.add(r1, ACC_DATA + M.MS_OFF_VBUMP)
    set_seed(a, 2, r1, 1)
    heap_ptr(a, r1, SEEDS)
    a.mov(r2, 3)
    prog_id(a, r3)
    heap_ptr(a, r4, VKEY)
    a.syscall("sol_create_program_address")
    a.exit()


