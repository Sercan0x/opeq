    a.jgt(r2, M.MAX_DATA, "cs_18")
    a.mov(r0, r1)
    a.add(r0, r2)
    a.stx(8, r9, S0, r0)
    a.ldx(1, r7, r1, 0)
    a.jlt(r7, 1, "cs_18")
    a.jgt(r7, M.MAX_IXS, "cs_18")
    a.mov(r6, r1)
    a.add(r6, 1)
    a.label("cs_ix")
    a.jeq(r7, 0, "cs_end")
    a.mov(r0, r6)
    a.add(r0, 33)
    a.ldx(8, r1, r9, S0)
    a.jgt(r0, r1, "cs_18")
    a.ldx(1, r0, r6, 32)
    a.jgt(r0, M.MAX_METAS, "cs_18")
    a.stx(8, r9, S1, r0)
    a.add(r6, 33)
    a.label("cs_meta")
    a.ldx(8, r0, r9, S1)
    a.jeq(r0, 0, "cs_data")
    a.mov(r0, r6)
    a.add(r0, 33)
    a.ldx(8, r1, r9, S0)
    a.jgt(r0, r1, "cs_18")
    a.ldx(1, r0, r6, 32)
    a.jset(r0, 0xFC, "cs_18")
    a.jset(r0, M.M_SIGNER, "cs_signer")
