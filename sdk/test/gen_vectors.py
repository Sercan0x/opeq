import hashlib
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, ROOT)

import mnemonic
import protocol
import wots
from solkit import b58decode, b58encode

PROGRAMS = {"mainnet": "HL598vrersxS5AUUV6NyzHgpSyK31xAmqMsqUhxzeKm8", "devnet": "424ckcA6GGswYmQbrGjQmzdfhk4G9eB2zD1gK8xLw7sN"}


def h(tag):
    return hashlib.sha256(tag.encode()).digest()


def vector(net):
    program = b58decode(PROGRAMS[net])
    master = h("opeq sdk vector master")
    key = mnemonic.tree(master, 0, program)
    aid = protocol.account_id(key.pub_seed, key.root)
    leaf = 7
    digest = h("opeq sdk vector digest")[:wots.N]
    sig, path = key.sign(leaf, digest)
    r = h("opeq sdk vector r")[:protocol.R_LEN]
    dest = h("opeq sdk vector dest")
    wallet = protocol.wallet_pda(aid, program)[0]
    inner = [(bytes(32), [(wallet, True, True), (dest, False, True)], bytes([2, 0, 0, 0]) + (1500000).to_bytes(8, "little"))]
    exec_digest = protocol.exec_digest(program, aid, 0, leaf, 123456789, inner, 42, r=r)
    return {
        "network": net,
        "master": master.hex(),
        "words": " ".join(mnemonic.to_words(master)),
        "pubSeed": key.pub_seed.hex(),
        "root": key.root.hex(),
        "aid": aid.hex(),
        "wallet": b58encode(wallet),
        "state": b58encode(protocol.state_pda(aid, program)[0]),
        "leaf": leaf,
        "digest": digest.hex(),
        "signature": sig.hex(),
        "path": path.hex(),
        "exec": {"epoch": 0, "leaf": leaf, "expiry": 123456789, "salt": 42, "r": r.hex(), "dest": b58encode(dest), "lamports": 1500000, "digest": exec_digest.hex()},
    }


if __name__ == "__main__":
    out = {"note": "generated by sdk/test/gen_vectors.py from the Python reference", "vectors": [vector(n) for n in PROGRAMS]}
    with open(os.path.join(os.path.dirname(__file__), "vectors.json"), "w") as f:
        json.dump(out, f, indent=1)
        f.write("\n")
    print("wrote", len(out["vectors"]), "vectors")
