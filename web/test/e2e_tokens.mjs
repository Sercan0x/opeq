import { readFileSync } from "fs";
import { createPrivateKey, sign as edSign } from "crypto";
import { Engine } from "../lib/engine.js";
import { localCompute } from "../lib/compute.js";
import { MemoryStore } from "../lib/vaultstore.js";
import * as T from "../lib/tokens.js";
import { Rpc, pubkey, b58encode, concat, u32, u64, SYSTEM } from "../lib/solana.js";
const raw = new Uint8Array(JSON.parse(readFileSync(new URL("../../devnet-key.json", import.meta.url))));
const der = Buffer.concat([Buffer.from("302e020100300506032b657004220420", "hex"), Buffer.from(raw.slice(0, 32))]);
const sk = createPrivateKey({ key: der, format: "der", type: "pkcs8" });
const payerPub = raw.slice(32);
const payer = { key: () => payerPub, sign: async (tx) => { const o = new Uint8Array(tx); o.set(edSign(null, Buffer.from(tx.slice(65)), sk), 1); return o; } };
const rpc = new Rpc("https://api.devnet.solana.com");
const engine = new Engine({ rpc, program: "424ckcA6GGswYmQbrGjQmzdfhk4G9eB2zD1gK8xLw7sN", store: new MemoryStore(), compute: localCompute, payer });
engine.log = (m) => console.log("   log:", m);
let fail = 0; const ok = (n, c) => { console.log((c ? "PASS " : "FAIL ") + n); if (!c) fail++; };
const { record } = await engine.create("token-test-pw-1"); await engine.save(record); await engine.init(record);
const s = await engine.unlock(record, "token-test-pw-1");
await engine.submit([SYSTEM, [[payerPub, true, true], [s.wallet, false, true]], concat(u32(2), u64(200_000_000))], (await rpc.slot()) + 150, 50000);
const alt = await rpc.lookupTable(T.DEMO.alt);
ok(`shared lookup table has ${alt.addresses.length} addresses`, alt.addresses.length === 13);
const amtIn = 50_000_000n;
const q = await T.quote(rpc, true, amtIn);
const sig1 = await s.exec(T.swapInner(s.wallet, payerPub, true, amtIn, q * 99n / 100n), 600000, null, [alt]);
const tokAta = T.ata(s.wallet, T.DEMO.mint);
const got = await rpc.tokenAmount(tokAta);
ok(`swap 0.05 SOL -> ${T.formatAmount(got, 6)} DEMO (quote ${T.formatAmount(q, 6)})`, got >= q * 99n / 100n);
const toks = await rpc.tokenAccounts(s.wallet);
ok(`token list shows DEMO`, toks.some((t) => t.mint === b58encode(T.DEMO.mint) && t.amount === got));
const bob = pubkey("AR7MtmqiWkrSqBfj6w196aQmdzRPoQ3juAnAZtqnuqzZ");
const half = got / 2n;
const bobAta = T.ata(bob, T.DEMO.mint);
const before = (await rpc.account(bobAta)) ? await rpc.tokenAmount(bobAta) : 0n;
await s.exec([T.createAtaIdempotent(payerPub, bob, T.DEMO.mint), T.transferChecked(T.TOKEN, tokAta, T.DEMO.mint, bobAta, s.wallet, half, 6)], 400000, null, [alt]);
ok("send DEMO tokens to another wallet", (await rpc.tokenAmount(bobAta)) === before + half);
const solBefore = await rpc.balance(s.wallet);
const rest = await rpc.tokenAmount(tokAta);
const q2 = await T.quote(rpc, false, rest);
await s.exec(T.swapInner(s.wallet, payerPub, false, rest, q2 * 99n / 100n), 600000, null, [alt]);
const solAfter = await rpc.balance(s.wallet);
ok(`swap DEMO back -> +${(solAfter - solBefore) / 1e9} SOL`, solAfter - solBefore >= Number(q2 * 99n / 100n));
console.log(fail ? `FAILED ${fail}` : "ALL PASSED");
