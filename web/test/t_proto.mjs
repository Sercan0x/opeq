import { readFileSync } from "fs";
import * as W from "../lib/wots.js";
import * as M from "../lib/mnemonic.js";
import * as P from "../lib/protocol.js";
import { b58encode, b58decode, hex, unhex, u32, u64, concat, SYSTEM } from "../lib/solana.js";
import { sha256 } from "../lib/sha256.js";
const v = JSON.parse(readFileSync(new URL("./vectors.json", import.meta.url)));
let fail = 0;
const ok = (n, c) => { console.log((c ? "PASS " : "FAIL ") + n); if (!c) fail++; };
const master = unhex(v.master);
ok("words match python", M.toWords(master).join(" ") === v.words);
ok("words roundtrip", hex(M.fromWords(v.words)) === v.master);
const s = M.treeSeeds(master, 0);
ok("tree seeds match", hex(s.skSeed) === v.sk0 && hex(s.pubSeed) === v.pub0);
ok("epoch 1 pub seed", hex(M.treeSeeds(master, 1).pubSeed) === v.pub1);
const program = unhex(v.program);
ok("base58 roundtrip", b58encode(program) === v.program_b58 && hex(b58decode(v.program_b58)) === v.program);
const aid = P.accountId(unhex(v.pub0), unhex(v.root0));
ok("account id", hex(aid) === v.aid);
const st = P.statePda(aid, program), wa = P.walletPda(aid, program);
ok("state pda + bump", b58encode(st.key) === v.state && st.bump === v.sbump);
ok("wallet pda + bump", b58encode(wa.key) === v.wallet && wa.bump === v.wbump);
const tree = M.deriveTree(master, 0);
const bob = sha256(new TextEncoder().encode("bob"));
const inner = [[SYSTEM, [[wa.key, true, true], [bob, false, true]], concat(u32(2), u64(12345))]];
const r = unhex(v.r);
const g = P.grind(P.execHasher(program, aid, 1, 5, 999, inner, r), 4096);
ok(`grind picks same salt ${g.salt} cost ${g.cost}`, g.salt === v.salt && hex(g.digest) === v.digest && g.cost === v.cost);
const { sig, path } = tree.sign(5, g.digest);
const data = P.buildExec(5, 999, g.salt, r, sig, path, inner, [st.key, wa.key, SYSTEM, bob]);
ok("exec instruction bytes identical", hex(data) === v.exec_data);
const t1 = M.deriveTree(master, 1);
ok("epoch 1 root", hex(t1.root) === v.root1);
const rg = P.grind(P.rekeyHasher(program, aid, 0, 7, 555, t1.pubSeed, t1.root, r), 512);
const rs = tree.sign(7, rg.digest);
ok("rekey instruction bytes identical", hex(P.buildRekey(7, 555, rg.salt, r, rs.sig, rs.path, t1.pubSeed, t1.root)) === v.rk_data);
ok("init bytes identical", hex(P.buildInit(unhex(v.pub0), unhex(v.root0), 1500000)) === v.init_data);
const t0 = Date.now(); P.grind(P.execHasher(program, aid, 1, 5, 999, inner, r)); 
console.log(`full grind 2^17: ${Date.now() - t0} ms`);
console.log(fail ? `FAILED ${fail}` : "ALL PASSED");
