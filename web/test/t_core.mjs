import { readFileSync } from "fs";
import { sha256 } from "../lib/sha256.js";
import * as W from "../lib/wots.js";
const v = JSON.parse(readFileSync(new URL("./vectors.json", import.meta.url)));
const hex = (b) => Buffer.from(b).toString("hex");
const unhex = (h) => new Uint8Array(Buffer.from(h, "hex"));
let fail = 0;
const ok = (name, c) => { console.log((c ? "PASS " : "FAIL ") + name); if (!c) fail++; };
ok("sha empty", hex(sha256(new Uint8Array(0))) === v.sha_empty);
ok("sha abc", hex(sha256(new TextEncoder().encode("abc"))) === v.sha_abc);
const long = new Uint8Array(1280); for (let i = 0; i < 1280; i++) long[i] = i & 255;
ok("sha 1280 bytes", hex(sha256(long)) === v.sha_long);
const t0 = Date.now();
const tree = W.TreeKey.generate(unhex(v.sk0), unhex(v.pub0));
const dt = Date.now() - t0;
ok(`tree root matches python (keygen ${dt} ms)`, hex(tree.root) === v.root0);
ok("leaf 5 matches", hex(tree.levels[0][5]) === v.leaf5);
const { sig, path } = tree.sign(5, unhex(v.digest));
ok("signature bytes match python", hex(sig) === v.sig && hex(path) === v.path);
ok("js verify accepts", W.verify(tree.pubSeed, tree.root, 5, unhex(v.digest), sig, path));
const bad = unhex(v.digest); bad[0] ^= 1;
ok("js verify rejects tampered digest", !W.verify(tree.pubSeed, tree.root, 5, bad, sig, path));
console.log(fail ? `FAILED ${fail}` : "ALL PASSED");
