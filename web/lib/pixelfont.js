export function glyph(ch) {
  return (G[ch] || G[ch.toUpperCase()] || G["?"]).split(" ");
}

export function drawText(ctx, text, x, y, size, color) {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of text) {
    glyph(ch).forEach((row, j) => {
      for (let i = 0; i < row.length; i++) if (row[i] === "1") ctx.fillRect(cx + i * size, y + j * size, size, size);
    });
    cx += 6 * size;
  }
}

export function textWidth(text, size) {
  return text.length * 6 * size - size;
}

export function renderPixelHeadings(root = document) {
  for (const el of root.querySelectorAll("[data-px]")) {
    if (el.dataset.pxDone) continue;
    el.dataset.pxDone = "1";
    const text = el.dataset.px;
    const size = Number(el.dataset.pxSize || 3);
    const color = getComputedStyle(el).color;
    const lowercase = /[opeq]/.test(text);
    const h = (lowercase ? 9 : 7) * size;
    const label = el.textContent;
    el.textContent = "";
    for (const word of text.split(" ")) {
      const c = document.createElement("canvas");
      c.width = textWidth(word, size);
      c.height = h;
      c.className = "px-canvas px-word";
      c.setAttribute("aria-hidden", "true");
      drawText(c.getContext("2d"), word, 0, 0, size, color);
      el.append(c);
    }
    const span = document.createElement("span");
    span.className = "sr-only";
    span.textContent = label;
    el.append(span);
  }
}
